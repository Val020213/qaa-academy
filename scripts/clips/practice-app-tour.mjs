import { record, SITE } from "./lib.mjs"
await record("practice-app-tour", async ({ page, mark, click, type, pause }) => {
  await page.goto(SITE + "/#/practice")
  await page.getByTestId("login-email").waitFor()
  await pause(800); mark()
  await type(page.getByTestId("login-email"), "qa@example.com")
  await type(page.getByTestId("login-password"), "wrong")
  await click(page.getByTestId("login-submit"))
  await pause(1500)
  await page.getByTestId("login-password").fill("")
  await type(page.getByTestId("login-password"), "Playwright123")
  await click(page.getByTestId("login-submit"))
  await pause(1500)
  await type(page.getByTestId("cases-input"), "Login with a blocked user", 45)
  await click(page.getByTestId("cases-add"))
  await pause(700)
  await type(page.getByTestId("cases-input"), "Add item to cart", 45)
  await click(page.getByTestId("cases-add"))
  await pause(900)
  await click(page.locator('[data-testid^="cases-toggle-"]').first())
  await pause(1200)
  await click(page.getByTestId("report-load"))
  await page.getByTestId("report-result").waitFor()
  await pause(1500)
})
