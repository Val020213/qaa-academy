import { record, SHOP } from "./lib.mjs"
import { reset, signIn } from "./shop.mjs"
await reset()
await record("shop-delete-dialog", async ({ page, mark, click, type, pause }) => {
  await page.goto(SHOP + "/login")
  await signIn(page, async (l) => l.click(), async (l, t) => l.fill(t), "admin@qa-shop.test", "Admin123!")
  await page.waitForURL(/dashboard/, { timeout: 60000 })
  await page.goto(SHOP + "/products")
  await page.getByTestId("products-table").waitFor()
  await pause(500); mark()
  const del = page.locator('[data-testid^="products-delete-"]').first()
  await pause(600)
  await click(del)
  await page.getByTestId("confirm-delete-dialog").waitFor()
  await pause(1600)
  await click(page.getByTestId("confirm-delete-cancel"))
  await pause(1200)
  await click(del)
  await page.getByTestId("confirm-delete-dialog").waitFor()
  await pause(1000)
  await click(page.getByTestId("confirm-delete-button"))
  await page.getByTestId("products-message").waitFor()
  await pause(2200)
})
await reset()
